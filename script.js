let currentLang = localStorage.getItem('portfolioLang') || 'ar';

// نظام إدارة المظاهر (تم إصلاح التعارض بنجاح)
const themes = ['light', 'dark', 'sepia'];
let currentTheme = localStorage.getItem('siteTheme') || 'light';

function applyTheme(theme) {
    const html = document.documentElement;
    html.classList.remove('dark', 'theme-sepia');
    
    if (theme === 'dark') {
        html.classList.add('dark');
    } else if (theme === 'sepia') {
        html.classList.add('theme-sepia');
    }
    
    const icon = document.getElementById('themeIcon');
    if (icon) {
        if (theme === 'light') {
            icon.textContent = 'light_mode';
            icon.style.color = '#eab308';
            icon.style.transform = 'rotate(0deg)';
        } else if (theme === 'dark') {
            icon.textContent = 'dark_mode';
            icon.style.color = '#a5b4fc';
            icon.style.transform = 'rotate(360deg)';
        } else if (theme === 'sepia') {
            icon.textContent = 'visibility';
            icon.style.color = '#8a5c2e';
            icon.style.transform = 'rotate(0deg)';
        }
    }
    
    localStorage.setItem('siteTheme', theme);
    currentTheme = theme;
}

function getThemeNameAr(theme) {
    if (theme === 'light') return 'المضيء ☀️';
    if (theme === 'dark') return 'المظلم 🌙';
    return 'الدافئ المريح للعين ☕';
}

// نظام تبديل وتغيير نوع وحجم الخطوط الجديد المضاف
const fonts = ['font-kufi', 'font-cairo', 'font-amiri'];
let currentFont = localStorage.getItem('siteFont') || 'font-kufi';

function applyFont(fontClass) {
    const body = document.body;
    fonts.forEach(f => body.classList.remove(f));
    body.classList.add(fontClass);
    localStorage.setItem('siteFont', fontClass);
    currentFont = fontClass;
}

function getFontNameAr(font) {
    if (font === 'font-kufi') return 'الكوفي الحديث 📱';
    if (font === 'font-cairo') return 'القاهري الفاخر 💎';
    return 'النسخ الأميري العريق ✒️';
}

function setLanguage(lang) {
    currentLang = lang;
    localStorage.setItem('portfolioLang', lang);
    
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            el.textContent = translations[lang][key];
        }
    });

    const langBtn = document.getElementById('langToggle');
    if (langBtn) langBtn.textContent = lang === 'ar' ? 'EN' : 'AR';
    renderProjects();
}

function renderProjects() {
    const container = document.getElementById('projectsContainer');
    if (!container) return;
    
    container.innerHTML = '';
    if (typeof projects === 'undefined') return;

    projects.forEach(project => {
        const title = currentLang === 'ar' ? project.titleAr : project.titleEn;
        const description = currentLang === 'ar' ? project.descriptionAr : project.descriptionEn;
        const tags = currentLang === 'ar' ? project.tagsAr : project.tagsEn;
        const moreBtnText = currentLang === 'ar' ? 'تفاصيل أكثر' : 'More Details';

        const card = document.createElement('div');
        card.className = "bg-white dark:bg-slate-900 rounded-2xl overflow-hidden border border-slate-200 dark:border-slate-800 shadow-md hover:shadow-xl transition-all duration-300 flex flex-col justify-between";
        card.innerHTML = `
            <div>
                <img src="${project.image}" alt="${title}" class="w-full h-48 object-cover">
                <div class="p-6">
                    <h3 class="text-xl font-bold">${title}</h3>
                    <p class="text-slate-600 dark:text-slate-400 mt-2 text-sm leading-relaxed">${description}</p>
                    <div class="flex flex-wrap gap-2 mt-4">
                        ${tags.map(tag => `<span class="px-2 py-1 bg-indigo-50 dark:bg-indigo-950 text-indigo-600 dark:text-indigo-400 rounded text-xs font-semibold">${tag}</span>`).join('')}
                    </div>
                </div>
            </div>
            <div class="p-6 pt-0">
                <a href="project-details.html?id=${project.id}" class="inline-flex items-center gap-2 text-indigo-600 dark:text-indigo-400 font-bold hover:gap-3 transition-all text-sm">
                    <span>${moreBtnText}</span>
                    <span class="material-symbols-outlined text-sm">arrow_forward</span>
                </a>
            </div>
        `;
        container.appendChild(card);
    });
}

function showToast(message, type = 'success') {
    const toast = document.getElementById('toast');
    if (!toast) return;
    toast.textContent = message;
    toast.className = `fixed bottom-6 right-6 z-50 p-4 rounded-xl text-white font-semibold transition-all shadow-xl ${type === 'success' ? 'bg-emerald-500' : 'bg-rose-500'}`;
    toast.classList.remove('hidden');
    
    setTimeout(() => {
        toast.classList.add('hidden');
    }, 4000);
}

// تهيئة التفاعلات البرمجية الكاملة والموحدة
document.addEventListener('DOMContentLoaded', () => {
    setLanguage(currentLang);
    applyTheme(currentTheme);
    applyFont(currentFont);

    // تفعيل مفتاح الثيمات الحلقي
    const themeBtn = document.getElementById('themeToggle');
    if (themeBtn) {
        themeBtn.addEventListener('click', () => {
            const nextIndex = (themes.indexOf(currentTheme) + 1) % themes.length;
            applyTheme(themes[nextIndex]);
            showToast(
                currentLang === 'ar' ? `تم الانتقال إلى المظهر ${getThemeNameAr(themes[nextIndex])}` : `Theme changed to: ${themes[nextIndex].toUpperCase()}`,
                'success'
            );
        });
    }

    // تفعيل مفتاح الخطوط الحلقي الجديد المضاف بجانب الثيمات
    const fontBtn = document.getElementById('fontToggle');
    if (fontBtn) {
        fontBtn.addEventListener('click', () => {
            const nextIndex = (fonts.indexOf(currentFont) + 1) % fonts.length;
            applyFont(fonts[nextIndex]);
            showToast(
                currentLang === 'ar' ? `تم تغيير خط الموقع إلى: ${getFontNameAr(fonts[nextIndex])}` : `Font changed successfully`,
                'success'
            );
        });
    }

    const langBtn = document.getElementById('langToggle');
    if (langBtn) {
        langBtn.addEventListener('click', () => {
            setLanguage(currentLang === 'ar' ? 'en' : 'ar');
        });
    }

    const contactForm = document.getElementById('contactForm');
    if (contactForm) {
        contactForm.addEventListener('submit', async (e) => {
            e.preventDefault();
            const submitBtn = document.getElementById('submitBtn');
            const submitText = document.getElementById('submitText');
            const submitIcon = document.getElementById('submitIcon');

            submitBtn.disabled = true;
            submitIcon.classList.add('animate-spin');
            submitIcon.textContent = 'autorenew';
            submitText.textContent = currentLang === 'ar' ? 'جاري الإرسال...' : 'Sending...';

            const formData = new FormData(contactForm);

            try {
                const response = await fetch(contactForm.action, {
                    method: 'POST',
                    body: formData,
                    headers: { Accept: 'application/json' }
                });

                if (!response.ok) throw new Error('Form submission failed');

                showToast(currentLang === 'ar' ? 'تم إرسال الرسالة بنجاح، شكراً لتواصلك!' : 'Message sent successfully! Thank you.', 'success');
                contactForm.reset();
            } catch (error) {
                showToast(currentLang === 'ar' ? 'عذراً! فشل إرسال الرسالة.' : 'Failed to send message.', 'error');
            } finally {
                submitBtn.disabled = false;
                submitIcon.classList.remove('animate-spin');
                submitIcon.textContent = 'send';
                submitText.textContent = currentLang === 'ar' ? 'إرسال الرسالة' : 'Send Message';
            }
           
        });
    }
});

 // تفاعلية القائمة المنسدلة وزر الهامبرغر على شاشات الموبايل
document.addEventListener('DOMContentLoaded', () => {
    const menuToggle = document.getElementById('menuToggle');
    const mobileMenu = document.getElementById('mobileMenu');
    const menuIcon = document.getElementById('menuIcon');

    if (menuToggle && mobileMenu) {
        menuToggle.addEventListener('click', () => {
            // فتح أو إغلاق القائمة
            mobileMenu.classList.toggle('hidden');
            
            // تغيير أيقونة الزر بين شكل الهامبرغر (menu) وشكل الإغلاق (close)
            if (mobileMenu.classList.contains('hidden')) {
                menuIcon.textContent = 'menu';
            } else {
                menuIcon.textContent = 'close';
            }
        });

        // إغلاق القائمة المنسدلة تلقائياً عند الضغط على أي رابط بداخلها
        mobileMenu.querySelectorAll('a').forEach(link => {
            link.addEventListener('click', () => {
                mobileMenu.classList.add('hidden');
                menuIcon.textContent = 'menu';
            });
        });
    }


 
});